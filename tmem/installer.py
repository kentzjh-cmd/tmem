from tmem import logger
from tmem.store import ProjectMemoryStore


def resolve_dsh_entry_js() -> Optional[Path]:
    """
    Dynamically locate `@deepseek-ai/dsh/package.json` across Linux, macOS, and Windows.
    Checks DSH_PACKAGE_ENTRY, `dsh` executable symlink/prefix ancestors, `npm root -g`,
    and standard global node_modules locations. Node's `createRequire` uses this
    file's directory to resolve `@deepseek-ai/cordis` and `@deepseek-ai/dsh-commands`.
    """
    env_entry = os.environ.get("DSH_PACKAGE_ENTRY")
    if env_entry:
        ep = Path(env_entry).expanduser()
        if ep.is_file():
            return ep.resolve()

    dsh_bin = shutil.which("dsh")
    if dsh_bin:
        try:
            resolved_bin = Path(dsh_bin).resolve()
            for anc in [resolved_bin.parent, *resolved_bin.parents][:5]:
                for cand in (
                    anc / "package.json",
                    anc / "node_modules" / "@deepseek-ai" / "dsh" / "package.json",
                    anc / "lib" / "node_modules" / "@deepseek-ai" / "dsh" / "package.json",
                ):
                    if cand.is_file() and cand.parent.name == "dsh":
                        return cand.resolve()
        except OSError:
            pass

    npm_bin = shutil.which("npm") or shutil.which("npm.cmd")
    if npm_bin:
        try:
            res = subprocess.run(
                [npm_bin, "root", "-g"],
                capture_output=True,
                text=True,
                timeout=5,
                check=False,
            )
            if res.returncode == 0 and res.stdout.strip():
                cand = Path(res.stdout.strip()) / "@deepseek-ai" / "dsh" / "package.json"
                if cand.is_file():
                    return cand.resolve()
        except (subprocess.SubprocessError, OSError):
            pass

    for fallback in (
        Path("/usr/lib/node_modules/@deepseek-ai/dsh/package.json"),
        Path("/usr/local/lib/node_modules/@deepseek-ai/dsh/package.json"),
        Path.home() / ".npm-global" / "lib" / "node_modules" / "@deepseek-ai" / "dsh" / "package.json",
    ):
        if fallback.is_file():
            return fallback.resolve()
    return None


def install_invisible_integration(
    workspace_root: str,
    agents: Optional[List[str]] = None,
    install_git_hook: bool = True,
) -> Dict[str, Any]:
    """Set up DSH plugin hooks, `/tmem` skill, AGENTS.md protocol, and Git post-commit hook."""
    ws = Path(workspace_root).resolve()
    target_agents = [a.strip().lower() for a in (agents or ["dsh"]) if a and a.strip()]
    store = ProjectMemoryStore(str(ws))
    store.ensure_initialized(init_project=True)

    installed: Dict[str, Any] = {"workspace": str(ws), "agents": [], "git_hook": False}
    cli_cmd = "python3 -m tmem.cli"

    if "dsh" in target_agents:
        plugin_src = Path(__file__).resolve().parent / "dsh_plugin.mjs"
        dsh_plugin_dir = ws / ".dsh" / "plugins"
        dsh_plugin_dir.mkdir(parents=True, exist_ok=True)
        dsh_plugin_dst = dsh_plugin_dir / "tmem-dsh-plugin.mjs"
        if plugin_src.exists():
            dsh_plugin_dst.write_text(plugin_src.read_text(encoding="utf-8"), encoding="utf-8")

        patch_yaml = (
            "# Generated by tmem init for DeepSeek Harness (@deepseek-ai/dsh)\n"
            "- insert:\n"
            "    - id: tmem\n"
            "      name: ./.dsh/plugins/tmem-dsh-plugin.mjs\n"
        )
        ws_patch_path = ws / ".dsh" / "tmem.patch.yml"
        ws_patch_path.write_text(patch_yaml, encoding="utf-8")

        global_plugin_path = str(plugin_src if plugin_src.exists() else dsh_plugin_dst)
        home_patch_yaml = (
            "# Generated by tmem init for DeepSeek Harness (@deepseek-ai/dsh)\n"
            "- insert:\n"
            "    - id: tmem\n"
            f"      name: {json.dumps(global_plugin_path)}\n"
        )
        dsh_home = Path(os.environ.get("DSH_HOME") or (Path.home() / ".dsh"))
        try:
            dsh_home.mkdir(parents=True, exist_ok=True)
            home_patch = dsh_home / "cordis.patch.yml"
            if home_patch.exists():
                existing_patch = home_patch.read_text(encoding="utf-8")
                if (
                    "id: tmem" not in existing_patch
                    and "tmem-dsh-plugin.mjs" not in existing_patch
                    and "dsh_plugin.mjs" not in existing_patch
                ):
                    home_patch.write_text(
                        existing_patch.rstrip() + "\n" + home_patch_yaml, encoding="utf-8"
                    )
            else:
                home_patch.write_text(home_patch_yaml, encoding="utf-8")
        except OSError as e:
            logger.debug("Failed updating cordis.patch.yml: %s", e)

        dsh_skill_dir = ws / ".dsh" / "skills" / "tmem"
        dsh_skill_dir.mkdir(parents=True, exist_ok=True)
        dsh_skill_md = (
            "---\n"
            "name: tmem\n"
            "description: >-\n"
            "  Capture, slice, or query deterministic execution trace memories at project (.tmem/) scope.\n"
            "  Activate when the user types /tmem, /remember, or confirms saving the current session's effective execution path.\n"
            "---\n\n"
            "# tmem Execution Trace Memory Skill (DSH)\n\n"
            "## Commands\n\n"
            "1. **Save Memory Trace**:\n"
            f"   `{cli_cmd} capture --agent dsh`\n"
            "2. **Check Memory & Telemetry Status**:\n"
            f"   `{cli_cmd} status`\n"
        )
        (dsh_skill_dir / "SKILL.md").write_text(dsh_skill_md, encoding="utf-8")

        ws_agents_md = ws / "AGENTS.md"
        dsh_rules_section = (
            "# tmem Deterministic Engineering Memory & Milestone Protocol (DSH)\n\n"
            "## 1. Consuming Memory (`MEMORIES.md`, L2 Runtime Repairs & L1 Co-Change Hints)\n"
            "- **Living Memory Index (`MEMORIES.md`)**: When navigating or planning modifications in this repository, consult `MEMORIES.md` (or `MEM.md`) for verified environment commands, recurring co-change hints, and known error repairs.\n"
            "- **L2 Causal Repair Hints (Post-Execute)**: When a shell/test command fails and tmem injects a matching L2 repair action, verify and apply the fix before retrying blindly.\n"
            "- **L1 Co-Change Topology**: Treat recurring co-change hints (`<tmem_cochange_hint>` / `L1_TOPOLOGY`) as structural reminders and inspect partner files/tests before finishing.\n"
            "- **Progressive Disclosure**: Detailed playbooks are in `.tmem/traces/*.json`; full forensic step replay is in `.tmem/raw/*.raw.json` (`python3 -m tmem.cli inspect <id> --level raw`).\n\n"
            "## 2. Goal Completion & `/tmem` Memory Persistence\n"
            "- **Proactive Milestone Prompt**: When you complete a non-trivial coding, debugging, or environment setup goal (or when `<tmem_milestone_reached>` is injected), append a concise one-line prompt at the end of your response asking whether to persist the memory trace:\n"
            "  > 💡 *是否需要将本次有效执行路径沉淀为记忆？（输入 `/tmem` 或 `/remember [备注]` 保存）*\n"
            "- **Executing Persistence**: If the user asks to save/record memory via natural language or `/tmem`, run:\n"
            f"  `{cli_cmd} capture --agent dsh`\n"
        )
        if ws_agents_md.exists():
            cur_agents = ws_agents_md.read_text(encoding="utf-8")
            if "tmem Speculative Execution Memory" not in cur_agents and "tmem Deterministic Engineering Memory" not in cur_agents:
                ws_agents_md.write_text(
                    cur_agents.rstrip() + "\n\n" + dsh_rules_section, encoding="utf-8"
                )
        else:
            ws_agents_md.write_text(dsh_rules_section, encoding="utf-8")

        installed["agents"].append(
            "dsh (.dsh/plugins/tmem-dsh-plugin.mjs + .dsh/tmem.patch.yml + ~/.dsh/cordis.patch.yml + .dsh/skills/tmem + AGENTS.md)"
        )

    store.sync_memories_markdown()
    installed["memories_doc"] = str(ws / "MEMORIES.md")

    if install_git_hook and (ws / ".git").exists():
        hooks_dir = ws / ".git" / "hooks"
        hooks_dir.mkdir(parents=True, exist_ok=True)
        post_commit = hooks_dir / "post-commit"
        tmem_pkg_root = Path(__file__).resolve().parent.parent
        pkg_root_str = tmem_pkg_root.as_posix() if os.name == "nt" else str(tmem_pkg_root)
        py_exec_str = Path(sys.executable).as_posix()
        path_sep = ";" if os.name == "nt" else ":"
        quoted_root = shlex.quote(pkg_root_str)
        quoted_py = shlex.quote(py_exec_str)
        hook_block = (
            f"TMEM_PY={quoted_py}\n"
            'if [ ! -x "$TMEM_PY" ]; then\n'
            "  if command -v python3 >/dev/null 2>&1; then\n"
            "    TMEM_PY=python3\n"
            "  elif command -v python >/dev/null 2>&1; then\n"
            "    TMEM_PY=python\n"
            "  else\n"
            '    TMEM_PY=""\n'
            "  fi\n"
            "fi\n"
            'if [ -z "$TMEM_PY" ]; then\n'
            '  echo "[tmem] warning: post-commit hook skipped (python interpreter not found)" >&2\n'
            "else\n"
            f"  TMEM_PKG_ROOT={quoted_root}\n"
            f'  PYTHONPATH="${{TMEM_PKG_ROOT}}${{PYTHONPATH:+{path_sep}$PYTHONPATH}}" "$TMEM_PY" -m tmem.cli capture --agent dsh --quiet\n'
            "  TMEM_STATUS=$?\n"
            '  if [ "$TMEM_STATUS" -ne 0 ]; then\n'
            '    echo "[tmem] warning: post-commit hook failed with exit code $TMEM_STATUS (PYTHONPATH=$TMEM_PKG_ROOT)" >&2\n'
            "  fi\n"
            "fi\n"
        )
        if post_commit.exists():
            existing = post_commit.read_text(encoding="utf-8")
            if "tmem.cli capture" not in existing:
                post_commit.write_text(existing.rstrip() + "\n" + hook_block, encoding="utf-8")
        else:
            post_commit.write_text("#!/bin/sh\n" + hook_block, encoding="utf-8")
        post_commit.chmod(post_commit.stat().st_mode | stat.S_IEXEC)
        installed["git_hook"] = True

    return installed
