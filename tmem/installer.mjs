import { execFileSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  realpathSync,
  statSync,
  writeFileSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { logger } from "./index.mjs";
import { ProjectMemoryStore } from "./store.mjs";

const SELF_DIR = path.dirname(fileURLToPath(import.meta.url));

function whichExecutable(cmdName) {
  const pathEnv = process.env.PATH || "";
  const dirs = pathEnv.split(path.delimiter).filter(Boolean);
  const exts =
    process.platform === "win32"
      ? (process.env.PATHEXT || ".EXE;.CMD;.BAT;.COM").split(";")
      : [""];
  for (const dir of dirs) {
    for (const ext of exts) {
      const full = path.join(dir, cmdName + ext);
      try {
        if (existsSync(full) && statSync(full).isFile()) {
          return full;
        }
      } catch (_err) {
        // ignore
      }
    }
  }
  return null;
}

function shellQuote(arg) {
  return "'" + String(arg).replace(/'/g, "'\"'\"'") + "'";
}

export function resolveDshEntryJs() {
  const envEntry = process.env.DSH_PACKAGE_ENTRY;
  if (envEntry) {
    const expanded = envEntry.startsWith("~/")
      ? path.join(os.homedir(), envEntry.slice(2))
      : envEntry;
    try {
      if (existsSync(expanded) && statSync(expanded).isFile()) {
        return realpathSync(expanded);
      }
    } catch (_err) {
      // ignore
    }
  }

  const dshBin = whichExecutable("dsh");
  if (dshBin) {
    try {
      const resolvedBin = realpathSync(dshBin);
      let cur = path.dirname(resolvedBin);
      for (let i = 0; i < 5; i++) {
        const candidates = [
          path.join(cur, "package.json"),
          path.join(cur, "node_modules", "@deepseek-ai", "dsh", "package.json"),
          path.join(cur, "lib", "node_modules", "@deepseek-ai", "dsh", "package.json"),
        ];
        for (const cand of candidates) {
          try {
            if (
              existsSync(cand) &&
              statSync(cand).isFile() &&
              path.basename(path.dirname(cand)) === "dsh"
            ) {
              return realpathSync(cand);
            }
          } catch (_err) {
            // ignore
          }
        }
        const parent = path.dirname(cur);
        if (parent === cur) break;
        cur = parent;
      }
    } catch (_err) {
      // ignore
    }
  }

  const npmBin = whichExecutable("npm") || whichExecutable("npm.cmd");
  if (npmBin) {
    try {
      const rootOut = execFileSync(npmBin, ["root", "-g"], {
        encoding: "utf-8",
        timeout: 5000,
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
      if (rootOut) {
        const cand = path.join(rootOut, "@deepseek-ai", "dsh", "package.json");
        if (existsSync(cand) && statSync(cand).isFile()) {
          return realpathSync(cand);
        }
      }
    } catch (_err) {
      // ignore
    }
  }

  const home = os.homedir();
  for (const fallback of [
    "/usr/lib/node_modules/@deepseek-ai/dsh/package.json",
    "/usr/local/lib/node_modules/@deepseek-ai/dsh/package.json",
    path.join(home, ".npm-global", "lib", "node_modules", "@deepseek-ai", "dsh", "package.json"),
  ]) {
    try {
      if (existsSync(fallback) && statSync(fallback).isFile()) {
        return realpathSync(fallback);
      }
    } catch (_err) {
      // ignore
    }
  }
  return null;
}

export function installInvisibleIntegration(
  workspaceRoot,
  agents = null,
  installGitHook = true
) {
  const ws = path.resolve(workspaceRoot);
  const targetAgents = (agents || ["dsh"])
    .map((a) => String(a || "").trim().toLowerCase())
    .filter(Boolean);
  const store = new ProjectMemoryStore(ws);
  store.ensureInitialized(true);

  const installed = { workspace: ws, agents: [], git_hook: false };
  const cliCmd = "tmem";

  if (targetAgents.includes("dsh")) {
    const pluginSrc = path.join(SELF_DIR, "dsh_plugin.mjs");
    const dshPluginDir = path.join(ws, ".dsh", "plugins");
    mkdirSync(dshPluginDir, { recursive: true });
    const dshPluginDst = path.join(dshPluginDir, "tmem-dsh-plugin.mjs");
    if (existsSync(pluginSrc)) {
      writeFileSync(dshPluginDst, readFileSync(pluginSrc, "utf-8"), "utf-8");
    }

    const patchYaml =
      "# Generated by tmem init for DeepSeek Harness (@deepseek-ai/dsh)\n" +
      "- insert:\n" +
      "    - id: tmem\n" +
      "      name: ./plugins/tmem-dsh-plugin.mjs\n";
    writeFileSync(path.join(ws, ".dsh", "tmem.patch.yml"), patchYaml, "utf-8");

    const globalPluginPath = existsSync(pluginSrc) ? pluginSrc : dshPluginDst;
    const homePatchYaml =
      "# Generated by tmem init for DeepSeek Harness (@deepseek-ai/dsh)\n" +
      "- insert:\n" +
      "    - id: tmem\n" +
      `      name: ${JSON.stringify(globalPluginPath)}\n`;
    const dshHome = process.env.DSH_HOME || path.join(os.homedir(), ".dsh");
    try {
      mkdirSync(dshHome, { recursive: true });
      const homePatch = path.join(dshHome, "cordis.patch.yml");
      if (existsSync(homePatch)) {
        const existingPatch = readFileSync(homePatch, "utf-8");
        if (
          !existingPatch.includes("id: tmem") &&
          !existingPatch.includes("tmem-dsh-plugin.mjs") &&
          !existingPatch.includes("dsh_plugin.mjs")
        ) {
          writeFileSync(
            homePatch,
            existingPatch.trimEnd() + "\n" + homePatchYaml,
            "utf-8"
          );
        }
      } else {
        writeFileSync(homePatch, homePatchYaml, "utf-8");
      }
    } catch (err) {
      logger.debug("Failed updating cordis.patch.yml:", err?.message || err);
    }

    const dshSkillDir = path.join(ws, ".dsh", "skills", "tmem");
    mkdirSync(dshSkillDir, { recursive: true });
    const dshSkillMd =
      "---\n" +
      "name: tmem\n" +
      "description: >-\n" +
      "  Capture, slice, or query deterministic execution trace memories at project (.tmem/) scope.\n" +
      "  Activate when the user types /tmem, /remember, or confirms saving the current session's effective execution path.\n" +
      "---\n\n" +
      "# tmem Execution Trace Memory Skill (DSH)\n\n" +
      "## Commands\n\n" +
      "1. **Save Memory Trace**:\n" +
      `   \`${cliCmd} capture --agent dsh\`\n` +
      "2. **Check Memory & Telemetry Status**:\n" +
      `   \`${cliCmd} status\`\n`;
    writeFileSync(path.join(dshSkillDir, "SKILL.md"), dshSkillMd, "utf-8");

    const wsAgentsMd = path.join(ws, "AGENTS.md");
    const dshRulesSection =
      "# tmem Deterministic Engineering Memory & Milestone Protocol (DSH)\n\n" +
      "## 1. Consuming Memory (`MEMORIES.md`, L2 Runtime Repairs & L1 Co-Change Hints)\n" +
      "- **Living Memory Index (`MEMORIES.md`)**: When navigating or planning modifications in this repository, consult `MEMORIES.md` (or `MEM.md`) for verified environment commands, recurring co-change hints, and known error repairs.\n" +
      "- **L2 Causal Repair Hints (Post-Execute)**: When a shell/test command fails and tmem injects a matching L2 repair action, verify and apply the fix before retrying blindly.\n" +
      "- **L1 Co-Change Topology**: Treat recurring co-change hints (`<tmem_cochange_hint>` / `L1_TOPOLOGY`) as structural reminders and inspect partner files/tests before finishing.\n" +
      "- **Progressive Disclosure**: Detailed playbooks are in `.tmem/traces/*.json`; full forensic step replay is in `.tmem/raw/*.raw.json` (`tmem inspect <id> --level raw`).\n\n" +
      "## 2. Goal Completion & `/tmem` Memory Persistence\n" +
      "- **Proactive Milestone Prompt**: When you complete a non-trivial coding, debugging, or environment setup goal (or when `<tmem_milestone_reached>` is injected), append a concise one-line prompt at the end of your response asking whether to persist the memory trace:\n" +
      "  > 💡 *是否需要将本次有效执行路径沉淀为记忆？（输入 `/tmem` 或 `/remember [备注]` 保存）*\n" +
      "- **Executing Persistence**: If the user asks to save/record memory via natural language or `/tmem`, run:\n" +
      `  \`${cliCmd} capture --agent dsh\`\n`;

    if (existsSync(wsAgentsMd)) {
      const curAgents = readFileSync(wsAgentsMd, "utf-8");
      if (
        !curAgents.includes("tmem Speculative Execution Memory") &&
        !curAgents.includes("tmem Deterministic Engineering Memory")
      ) {
        writeFileSync(
          wsAgentsMd,
          curAgents.trimEnd() + "\n\n" + dshRulesSection,
          "utf-8"
        );
      }
    } else {
      writeFileSync(wsAgentsMd, dshRulesSection, "utf-8");
    }

    installed.agents.push(
      "dsh (.dsh/plugins/tmem-dsh-plugin.mjs + .dsh/tmem.patch.yml + ~/.dsh/cordis.patch.yml + .dsh/skills/tmem + AGENTS.md)"
    );
  }

  store.syncMemoriesMarkdown();
  installed.memories_doc = path.join(ws, "MEMORIES.md");

  if (installGitHook && existsSync(path.join(ws, ".git"))) {
    const hooksDir = path.join(ws, ".git", "hooks");
    mkdirSync(hooksDir, { recursive: true });
    const postCommit = path.join(hooksDir, "post-commit");
    const cliScriptPath = path.join(SELF_DIR, "cli.mjs");
    const quotedNode = shellQuote(process.execPath);
    const quotedCli = shellQuote(cliScriptPath);

    const hookBlock =
      `TMEM_NODE=${quotedNode}\n` +
      'if [ ! -x "$TMEM_NODE" ]; then\n' +
      "  if command -v node >/dev/null 2>&1; then\n" +
      "    TMEM_NODE=node\n" +
      "  else\n" +
      '    TMEM_NODE=""\n' +
      "  fi\n" +
      "fi\n" +
      `TMEM_CLI=${quotedCli}\n` +
      'if [ -z "$TMEM_NODE" ]; then\n' +
      '  echo "[tmem] warning: post-commit hook skipped (node runtime not found)" >&2\n' +
      'elif [ ! -f "$TMEM_CLI" ]; then\n' +
      '  echo "[tmem] warning: post-commit hook skipped (CLI entrypoint missing: $TMEM_CLI)" >&2\n' +
      "else\n" +
      '  "$TMEM_NODE" "$TMEM_CLI" capture --agent dsh --quiet\n' +
      "  TMEM_STATUS=$?\n" +
      '  if [ "$TMEM_STATUS" -ne 0 ]; then\n' +
      '    echo "[tmem] warning: post-commit hook failed with exit code $TMEM_STATUS (TMEM_CLI=$TMEM_CLI)" >&2\n' +
      "  fi\n" +
      "fi\n";

    if (existsSync(postCommit)) {
      const existing = readFileSync(postCommit, "utf-8");
      if (!existing.includes("tmem/cli.mjs") && !existing.includes("TMEM_CLI=")) {
        writeFileSync(postCommit, existing.trimEnd() + "\n" + hookBlock, "utf-8");
      }
    } else {
      writeFileSync(postCommit, "#!/bin/sh\n" + hookBlock, "utf-8");
    }
    try {
      const mode = statSync(postCommit).mode;
      chmodSync(postCommit, mode | 0o111);
    } catch (_err) {
      // ignore on platforms without posix chmod
    }
    installed.git_hook = true;
  }

  return installed;
}
