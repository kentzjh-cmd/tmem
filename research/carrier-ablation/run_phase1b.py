def prepare(root: Path, reps: int) -> None:
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)
    evidence = HARNESS / "abl-out"
    evidence.mkdir(parents=True, exist_ok=True)

    # ---- 1. sanitised seed workspace (fixture tree + the seeded .tmem store)
    seed = root / "seed"
    shutil.copytree(SEED_SOURCE, seed, symlinks=True)
    seed_agents = seed / "AGENTS.md"
    seed_memory_index = seed / "MEMORIES.md"
    keep_agents = seed_agents.read_text(encoding="utf-8") if seed_agents.exists() else ""
    keep_index = seed_memory_index.read_text(encoding="utf-8") if seed_memory_index.exists() else ""
    seed_info = sanitize_workspace(seed, keep_agents=False)
    # restore the two untracked files the clean removed (they are carriers /
    # instructions, not build artefacts) -- the control arms drop them again.
    (seed / "AGENTS.md").write_text(keep_agents, encoding="utf-8")
    if keep_index:
        (seed / "MEMORIES.md").write_text(keep_index, encoding="utf-8")
        (seed / "MEM.md").unlink(missing_ok=True)
        (seed / "MEM.md").symlink_to("MEMORIES.md")

    # ---- 2. prose carrier rendered from the very same episode records
    r = sh([sys.executable, str(ABL / "render_prose_carrier.py"), "--src", str(seed), "--out", str(root / "carrier")], timeout=300)
    print("[prep] carrier render:", r.stdout.strip()[-300:], r.stderr.strip()[-200:])
    if r.returncode != 0:
        raise SystemExit("[prep] FATAL: carrier equivalence check failed")
    prose = (root / "carrier" / "MEMORY.md").read_text(encoding="utf-8")

    # ---- 3. sanitised tmem package (what the container sees as /archive/tmem)
    pkg = root / "tmem-pkg"
    pkg.mkdir()
    shutil.copytree(REPO / "tmem", pkg / "tmem")
    shutil.copy2(REPO / "package.json", pkg / "package.json")
    shutil.copy2(REPO / "LICENSE", pkg / "LICENSE")

    # ---- 4. A2 mechanism ablation: a patched copy of the same package
    a2 = root / "tmem-a2"
    shutil.copytree(pkg, a2)
    hook = a2 / "tmem" / "hooks" / "dsh.mjs"
    text = hook.read_text(encoding="utf-8")
    old = '    if (preBlocks.length > 0) {\n      return { injectedContext: preBlocks.join("\\n\\n") };'
    new = (
        '    if (preBlocks.length > 0 && process.env.TMEM_ABLATE_NO_INJECT !== "1") {\n'
        '      return { injectedContext: preBlocks.join("\\n\\n") };'
    )
    if old not in text:
        raise SystemExit("[prep] FATAL: injection branch not found in hooks/dsh.mjs")
    hook.write_text(text.replace(old, new, 1), encoding="utf-8")
    (root / "a2_patch.json").write_text(
        json.dumps(
            {
                "patched_file": str(hook),
                "patch": 'if (preBlocks.length > 0 && process.env.TMEM_ABLATE_NO_INJECT !== "1")',
                "env": "TMEM_ABLATE_NO_INJECT=1",
                "diff": "single line, see a2_patch.diff",
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    (root / "a2_patch.diff").write_text(
        "\n".join(
            [
                "--- a/tmem/hooks/dsh.mjs",
                "+++ b/tmem/hooks/dsh.mjs",
                "@@",
                "-    if (preBlocks.length > 0) {",
                '+    if (preBlocks.length > 0 && process.env.TMEM_ABLATE_NO_INJECT !== "1") {',
            ]
        ),
        encoding="utf-8",
    )

    # ---- 5. PATH shims
    a2bin, blockbin = root / "a2bin", root / "blockbin"
    a2bin.mkdir()
    blockbin.mkdir()
    link = a2bin / "tmem"
    link.symlink_to(a2 / "tmem" / "cli.mjs")
    blk = blockbin / "tmem"
    blk.write_text(
        "#!/bin/sh\n"
        "echo '[ablation] the tmem CLI is not available in this arm' >&2\n"
        "exit 127\n",
        encoding="utf-8",
    )
    blk.chmod(0o755)

    # ---- 6. the prose injector (the copy the container may see)
    plugins = root / "plugins"
    plugins.mkdir()
    shutil.copy2(ABL / "md_carrier_plugin.mjs", plugins / "md_carrier_plugin.mjs")

    # ---- 7. arms
    manifest = []
    for arm in ARMS:
        for rep in range(1, reps + 1):
            ws = root / "arms" / arm / f"rep{rep}"
            ws.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(seed, ws, symlinks=True)
            sanitize_workspace(ws, keep_agents=True)
            entry = {"arm": arm, "rep": rep, "workspace": str(ws)}

            hook_file = ws / ".git" / "hooks" / "post-commit"
            if hook_file.exists():
                hook_file.unlink()

            if arm in ("A1", "A2"):
                env = dict(os.environ)
                env["DSH_HOME"] = str(root / "homes" / "init-tmp")
                (root / "homes" / "init-tmp").mkdir(parents=True, exist_ok=True)
                res = sh(["tmem", "init"], cwd=ws, env=env, timeout=300)
                entry["tmem_init_exit"] = res.returncode
                normalize_agents_md(ws)
                entry["patch"] = str(ws / ".dsh" / "tmem.patch.yml")
            else:
                shutil.rmtree(ws / ".tmem", ignore_errors=True)
                for f in ("MEMORY.md", "MEMORIES.md", "MEM.md"):
                    p = ws / f
                    if p.exists() or p.is_symlink():
                        p.unlink()
                if arm in ("B1", "B2"):
                    (ws / "MEMORY.md").write_text(prose, encoding="utf-8")
                    entry["memory_md_bytes"] = len(prose.encode("utf-8"))
                if arm == "B1":
                    d = ws / ".dsh"
                    d.mkdir(exist_ok=True)
                    (d / "md-carrier.patch.yml").write_text(
                        "# carrier-ablation: prose MD injector\n"
                        "- insert:\n"
                        "    - id: md-carrier\n"
                        f'      name: "{root / "plugins" / "md_carrier_plugin.mjs"}"\n',
                        encoding="utf-8",
                    )
                    entry["patch"] = str(d / "md-carrier.patch.yml")

            entry["has_tmem_store"] = (ws / ".tmem").exists()
            entry["has_memory_md"] = (ws / "MEMORY.md").exists()
            entry["has_memories_md"] = (ws / "MEMORIES.md").exists()
            entry["workspace_hits"] = keypoint_hits(ws, KEYPOINT_NEEDLES)
            manifest.append(entry)
            print(
                "[prep] %s rep%d: store=%s MEMORY.md=%s MEMORIES.md=%s"
                % (arm, rep, entry["has_tmem_store"], entry["has_memory_md"], entry["has_memories_md"]),
                flush=True,
            )

    (root / "arms_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    (evidence / "arms_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    (evidence / "seed_provenance.json").write_text(
        json.dumps(
            {
                "seed_source": str(SEED_SOURCE),
                "seed_sha_agents": sha256_file(SEED_SOURCE / "AGENTS.md") if (SEED_SOURCE / "AGENTS.md").exists() else None,
                "seed_sanitize": seed_info,
                "prose_sha256": sha256_file(root / "carrier" / "MEMORY.md"),
                "md_carrier_plugin_sha256": sha256_file(root / "plugins" / "md_carrier_plugin.mjs"),
                "tmem_pkg_sha256": sha256_file(pkg / "package.json"),
                "a2_hook_sha256": sha256_file(hook),
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    print("[prep] manifest ->", root / "arms_manifest.json")


