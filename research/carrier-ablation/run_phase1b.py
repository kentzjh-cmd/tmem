# ------------------------------------------------------------------- session
def make_home(root: Path, arm: str, rep: int, variant: str) -> tuple[Path, dict]:
    """A private DSH_HOME for ONE session (random name: not guessable)."""
    name = f"{arm.lower()}-r{rep}-{variant}-{secrets.token_hex(4)}"
    home = root / "homes" / name
    home.mkdir(parents=True)
    # ONLY the headless profile, and with symlinks kept as symlinks.
    #
    # Phase-1b attempt #1 copied the whole profiles tree with
    # `copytree(...)` (symlinks=False): the `web` profile's node_modules
    # links to multi-hundred-MB onnx/sherpa binaries, so every session home
    # became 2.4 GB and the disk died after two sessions (39 GB of copies).
    # The headless profile is 14 KB and is the only one `--profile headless`
    # ever loads.
    headless = REAL_HOME / "profiles" / "headless"
    if headless.exists():
        shutil.copytree(headless, home / "profiles" / "headless", symlinks=True)
    patch = strip_tmem_entry((REAL_HOME / "cordis.patch.yml").read_text(encoding="utf-8"))
    if arm == "B1":
        patch = patch.rstrip() + (
            "\n\n# carrier-ablation: prose MD injector (arm B1 only)\n"
            "- insert:\n"
            "    - id: md-carrier\n"
            f'      name: "{root / "plugins" / "md_carrier_plugin.mjs"}"\n'
        )
    (home / "cordis.patch.yml").write_text(patch, encoding="utf-8")
    return home, {"home": str(home), "name": name}


def docker_argv(root: Path, entry: dict, home: Path, prompt: str, api_key: str) -> list[str]:
    argv = [
        "docker", "run", "--rm",
        "--network", "bridge",
        "--user", "1000:1000",
        "--workdir", CONTAINER_WORKSPACE,
        "--env", f"HOME={CONTAINER_HOME}",
        "--env", f"DSH_HOME={CONTAINER_HOME}",
        "--env", f"{API_KEY_ENV}={api_key}",
        "--tmpfs", "/tmp:exec,size=64m",
        "-v", f"{entry['workspace']}:{CONTAINER_WORKSPACE}",
        "-v", f"{home}:{CONTAINER_HOME}",
        "-v", "/home/kent/.nvm:/home/kent/.nvm:ro",
        "-v", f"{root / 'tmem-pkg'}:/archive/tmem:ro",
        "-v", f"{root / 'tmem-a2'}:/home/kent/abl2/tmem-a2:ro",
        "-v", f"{root / 'a2bin'}:/home/kent/abl2/a2bin:ro",
        "-v", f"{root / 'blockbin'}:/home/kent/abl2/blockbin:ro",
        "-v", f"{root / 'plugins'}:/home/kent/abl2/plugins:ro",
        # the headless profile links its local plugin at
        # /archive/pentest_work_flow/dsh_secops_plugin -> bind it read-only so
        # the profile resolves exactly as it does on the host (no copy, no disk)
        "-v", "/archive/pentest_work_flow:/archive/pentest_work_flow:ro",
    ]
    path = f"{NODE_BIN}:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
    if entry["arm"] in ("B2", "C"):
        path = f"/home/kent/abl2/blockbin:{path}"
    elif entry["arm"] == "A2":
        path = f"/home/kent/abl2/a2bin:{path}"
    argv += ["--env", f"PATH={path}"]
    if entry["arm"] == "A2":
        argv += ["--env", "TMEM_ABLATE_NO_INJECT=1"]

    cmd = ["dsh", "--profile", "headless"]
    if entry.get("patch") and Path(entry["patch"]).exists():
        rel = Path(entry["patch"]).relative_to(entry["workspace"])
        cmd += ["--patch", str(Path(CONTAINER_WORKSPACE) / rel)]
    cmd += ["headless", prompt]
    argv += [IMAGE] + cmd
    return argv


def newest_transcript(home: Path) -> str | None:
    root = home / "sessions"
    best, best_mtime = None, -1.0
    if not root.exists():
        return None
    for path in root.rglob("session.v4.jsonl*"):
        try:
            m = path.stat().st_mtime
        except OSError:
            continue
        if m > best_mtime:
            best, best_mtime = path, m
    return str(best) if best else None


def run_one(root: Path, entry: dict, variant: str, prompt: str, api_key: str, timeout: int) -> dict:
    home, home_info = make_home(root, entry["arm"], entry["rep"], variant)
    out_dir = root / "raw" / entry["arm"] / f"rep{entry['rep']}" / variant
    out_dir.mkdir(parents=True, exist_ok=True)
    argv = docker_argv(root, entry, home, prompt, api_key)

    started = time.time()
    try:
        proc = subprocess.run(argv, capture_output=True, text=True, timeout=timeout)
        stdout, stderr, code = proc.stdout, proc.stderr, proc.returncode
    except subprocess.TimeoutExpired as exc:
        stdout = exc.stdout.decode() if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        stderr = exc.stderr.decode() if isinstance(exc.stderr, bytes) else (exc.stderr or "")
        code = -1
    elapsed = time.time() - started

    (out_dir / "stdout.log").write_text(stdout, encoding="utf-8")
    (out_dir / "stderr.log").write_text(stderr, encoding="utf-8")
    # the argv is evidence: it is the mount allow-list of the session. The API
    # key is redacted before it is written to disk.
    safe_argv = [a.replace(api_key, "<redacted>") if api_key in a else a for a in argv]
    record = {
        "arm": entry["arm"],
        "rep": entry["rep"],
        "variant": variant,
        "workspace": entry["workspace"],
        "container_workspace": CONTAINER_WORKSPACE,
        "dsh_home": str(home),
        "home_name": home_info["name"],
        "isolation": "docker:tmem-abl:iso (mount allow-list)",
        "docker_argv": safe_argv,
        "exit_code": code,
        "elapsed_sec": round(elapsed, 1),
        "stdout_bytes": len(stdout.encode("utf-8")),
        "stderr_bytes": len(stderr.encode("utf-8")),
        "prompt_sha": hashlib.sha256(prompt.encode("utf-8")).hexdigest()[:16],
        "transcript_path": newest_transcript(home),
    }
    (out_dir / "scene.json").write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")
    return record


def already_done(root: Path, entry: dict, variant: str) -> bool:
    d = root / "raw" / entry["arm"] / f"rep{entry['rep']}" / variant
    f = d / "scene.json"
    if not f.exists():
        return False
    try:
        rec = json.loads(f.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return False
    if rec.get("exit_code") != 0:
        return False
    tp = rec.get("transcript_path")
    return bool(tp) and Path(tp).exists()


