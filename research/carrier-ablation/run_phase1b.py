#!/usr/bin/env python3
"""Phase-1b runner for the carrier-ablation study.

What changed versus the phase-1 runner (run_ablation.py), and why
------------------------------------------------------------------
1. STRUCTURAL ISOLATION.  Phase 1 leaked: three control-arm sessions left
   their workspace and read another experiment's memory store.  Permissions on
   the host cannot stop that -- the agent runs as the same uid as the harness
   and can chmod anything it owns.  Every session therefore runs inside its own
   container (image ``tmem-abl:iso``) whose filesystem contains ONLY the
   protocol's allow-list:

       /work            <- this arm/rep's workspace (rw)
       /dsh-home       <- this session's own DSH_HOME (rw)
       /home/kent/.nvm <- node + the dsh package (ro)
       /archive/tmem   <- a sanitised copy of the tmem package (ro)
       ... plus the arm's PATH shims

   /home/kent/e2e, /home/kent/.dsh and /archive/tmem/docs are simply NOT THERE.

2. PER-SESSION DSH_HOME.  Phase 1 shared one home between nine sessions, so a
   session could read a sibling's transcript (which contains the injected
   memory).  Every (arm, rep, variant) now gets its own home, with a random
   directory name so it cannot be guessed from inside the container.

3. WORKSPACE HYGIENE.  The phase-1 workspaces still carried the compiled
   ``__pycache__`` of the FIXED code (``ensure_usable_price`` was greppable in
   ``src/ledger/__pycache__/*.pyc``).  Every workspace is now reset to the
   fixture with ``git checkout -- .`` + ``git clean -fdx`` before use, and the
   keypoint strings are re-checked (machine-readable).

4. INJECTION CADENCE PARITY.  The prose injector re-injected the carrier on
   every agent step (4-7 copies in phase 1) while tmem injects once per user
   turn.  md_carrier_plugin.mjs now keeps the tmem cadence.

Nothing else changed: the prompts, the keypoints and the thresholds are the
frozen ones from the oracle.

Usage
-----
  python3 run_phase1b.py prepare --exp-root /home/kent/abl2
  python3 run_phase1b.py smoke   --exp-root /home/kent/abl2
  python3 run_phase1b.py run     --exp-root /home/kent/abl2 --arms A1,A2,B1,B2,C \
      --variants free,zero --reps 3 --resume
"""

