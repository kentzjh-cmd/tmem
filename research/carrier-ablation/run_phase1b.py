MOUNT_TASK = "只回复 OK。不要修改任何文件，不要运行任何命令。"
TMEM_TOOLS = {"tmem_search", "tmem_expand", "tmem_lookup", "tmem_capture", "tmem_recall"}


def audit_transcript(path: Path) -> dict:
    """Tool list + injection markers of one session transcript."""
    out = {"tools": [], "tmem_injection": False, "md_injection": False, "events": 0,
           "tmem_injection_count": 0, "md_injection_count": 0}
    if not path.exists():
        return out
    try:
        import zstandard

        raw = path.read_bytes()
        dctx = zstandard.ZstdDecompressor()
        chunks, pos = [], 0
        while pos < len(raw):
            d = dctx.decompressobj()
            out_chunk = d.decompress(raw[pos:])
            chunks.append(out_chunk)
            consumed = len(raw) - pos - len(d.unused_data)
            if consumed <= 0:
                break
            pos += consumed
        text = b"".join(chunks).decode("utf-8", "replace")
    except ImportError:
        text = subprocess.run(["zstd", "-dc", str(path)], capture_output=True).stdout.decode("utf-8", "replace")
    tools: set[str] = set()
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            ev = json.loads(line)
        except json.JSONDecodeError:
            continue
        out["events"] += 1
        if ev.get("type") == "request/header":
            header = (ev.get("data") or {}).get("header") or {}
            for t in header.get("tools") or []:
                name = t.get("name") if isinstance(t, dict) else t
                if name:
                    tools.add(str(name))
        if ev.get("type") == "user/message":
            data = ev.get("data") or {}
            payload = "".join(
                c.get("text", "")
                for c in (data.get("content") or [])
                if isinstance(c, dict) and c.get("type") == "text"
            )
            if "<tmem_speculative_memory>" in payload:
                out["tmem_injection"] = True
                out["tmem_injection_count"] += 1
            if "项目工程决策记录" in payload or '"kind":"md-carrier"' in payload:
                out["md_injection"] = True
                out["md_injection_count"] += 1
    out["tools"] = sorted(tools)
    out["tmem_tools_present"] = bool(TMEM_TOOLS & set(tools))
    return out


def mountcheck(root: Path, arms_filter: list[str] | None = None) -> int:
    api_key = read_api_key()
    manifest = json.loads((root / "arms_manifest.json").read_text(encoding="utf-8"))
    results = []
    for entry in manifest:
        if entry["rep"] != 1:
            continue
        if arms_filter and entry["arm"] not in arms_filter:
            continue
        home, _ = make_home(root, entry["arm"], 1, "mount")
        argv = docker_argv(root, entry, home, MOUNT_TASK, api_key)
        started = time.time()
        proc = subprocess.run(argv, capture_output=True, text=True, timeout=600)
        elapsed = round(time.time() - started, 1)
        a = audit_transcript(Path(newest_transcript(home) or "/nonexistent"))
        arm = entry["arm"]
        if arm in ("A1", "A2"):
            # The trivial task contains no file anchor and no error signature,
            # so tmem's injector must NOT fire -- it fires on the real probe
            # prompts, and the scorer invalidates an A-arm session that shows
            # no injection at all (amendment A2 protocol rule).
            ok = a["tmem_tools_present"] and not a["tmem_injection"]
        elif arm == "B1":
            ok = (not a["tmem_tools_present"]) and a["md_injection"]
        else:
            ok = (not a["tmem_tools_present"]) and (not a["tmem_injection"]) and (not a["md_injection"])
        a.update(
            {
                "arm": arm,
                "exit_code": proc.returncode,
                "elapsed_sec": elapsed,
                "stdout_bytes": len(proc.stdout.encode()),
                "expectation_met": ok,
                "workspace": entry["workspace"],
                "dsh_home": str(home),
            }
        )
        results.append(a)
        print(
            "[mount] %s: tmem_tools=%s tmem_injection=%s md_injection=%s -> %s"
            % (arm, a["tmem_tools_present"], a["tmem_injection"], a["md_injection"], "OK" if ok else "FAIL"),
            flush=True,
        )
    out = HARNESS / "abl-out"
    out.mkdir(parents=True, exist_ok=True)
    mcf = out / "mount_check.json"
    merged: dict = {}
    if mcf.exists():
        try:
            for rec in json.loads(mcf.read_text(encoding="utf-8")):
                merged[rec["arm"]] = rec
        except json.JSONDecodeError:
            pass
    for rec in results:
        merged[rec["arm"]] = rec
    ordered = [merged[a] for a in ARMS if a in merged]
    mcf.write_text(json.dumps(ordered, ensure_ascii=False, indent=2), encoding="utf-8")
    bad = [r["arm"] for r in ordered if not r["expectation_met"]]
    print("[mount] all arms OK" if not bad else "[mount] FAILED arms: %s" % bad)
    return 0 if not bad else 5


# ---------------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("phase", choices=["prepare", "smoke", "mountcheck", "run"])
    ap.add_argument("--exp-root", default="/home/kent/abl2")
    ap.add_argument("--arms", default=",".join(ARMS))
    ap.add_argument("--variants", default="free,zero")
    ap.add_argument("--reps", type=int, default=3)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--resume", action="store_true")
    args = ap.parse_args()
    root = Path(args.exp_root)

    if args.phase == "prepare":
        prepare(root, args.reps)
        return 0
    if args.phase == "smoke":
        return smoke(root)
    if args.phase == "mountcheck":
        return mountcheck(root, [a.strip() for a in args.arms.split(",") if a.strip()] or None)

    oracle = json.loads((ABL / "oracle_carrier_ablation.json").read_text(encoding="utf-8"))
    prompts = oracle["prompts"]
    manifest = json.loads((root / "arms_manifest.json").read_text(encoding="utf-8"))
    api_key = read_api_key()
    arms = [a.strip() for a in args.arms.split(",") if a.strip()]
    variants = [v.strip() for v in args.variants.split(",") if v.strip()]

    summary = []
    for entry in manifest:
        if entry["arm"] not in arms or entry["rep"] > args.reps:
            continue
        for variant in variants:
            if args.resume and already_done(root, entry, variant):
                print("[abl2] skip %s rep%s %s (already succeeded)" % (entry["arm"], entry["rep"], variant), flush=True)
                continue
            prompt = prompts[variant]
            print("[abl2] %s rep%s %s ..." % (entry["arm"], entry["rep"], variant), flush=True)
            rec = run_one(root, entry, variant, prompt, api_key, args.timeout)
            summary.append(rec)
            print(
                "[abl2] done %s rep%s %s: exit=%s elapsed=%ss out=%sB"
                % (entry["arm"], entry["rep"], variant, rec["exit_code"], rec["elapsed_sec"], rec["stdout_bytes"]),
                flush=True,
            )
            (HARNESS / "abl-out" / "run_summary.json").write_text(
                json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8"
            )
    print("[abl2] all sessions done")
    return 0


