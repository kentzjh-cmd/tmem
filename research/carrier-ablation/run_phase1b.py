# ------------------------------------------------------------------ helpers
def sh(cmd: list[str], cwd: Path | None = None, env: dict | None = None, timeout: int = 600):
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)


def read_api_key() -> str:
    """Read the API key from the DSH credential store without echoing it."""
    text = CRED_FILE.read_text(encoding="utf-8")
    m = re.search(rf"^\s*{re.escape(API_KEY_ENV)}\s*:\s*(.+)$", text, re.MULTILINE)
    if not m:
        raise SystemExit(f"cannot find {API_KEY_ENV} in {CRED_FILE}")
    return m.group(1).strip().strip("'\"")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def strip_tmem_entry(patch_text: str) -> str:
    block = """# 1) tmem plugin — Generated by tmem init for DeepSeek Harness (@deepseek-ai/dsh)
- insert:
    - id: tmem
      name: "/archive/tmem/tmem/dsh_plugin.mjs"

"""
    if block in patch_text:
        return patch_text.replace(block, "")
    return re.sub(r"- insert:\n(?:\s+- id: tmem\n(?:.*\n)*?\n)*", "", patch_text)


def normalize_agents_md(ws: Path) -> None:
    p = ws / "AGENTS.md"
    text = p.read_text(encoding="utf-8") if p.exists() else ""
    idx = text.find(TMEM_AGENTS_MARKER)
    if idx >= 0:
        text = text[:idx].rstrip() + "\n"
    p.write_text(text.rstrip() + "\n" + NEUTRAL_AGENTS_TAIL, encoding="utf-8")


def sanitize_workspace(ws: Path, keep_agents: bool = True) -> dict:
    """Reset the workspace to the fixture and drop every build artefact.

    `git clean -fdx` is what removes the `__pycache__` of the FIXED code: in
    phase 1 those .pyc files still contained `ensure_usable_price`, so a
    control arm could have answered Q3 from the code artefacts.
    """
    r1 = sh(["git", "checkout", "--", "."], cwd=ws)
    # `-e .tmem` keeps the seeded memory store (it is git-ignored, and it IS
    # the tmem carrier for the A arms); everything else untracked goes.
    r2 = sh(["git", "clean", "-fdx", "-e", ".tmem"], cwd=ws)
    if keep_agents:
        normalize_agents_md(ws)
    return {
        "checkout_rc": r1.returncode,
        "clean_rc": r2.returncode,
        "cleaned": r2.stdout.strip().splitlines()[:20],
    }


def keypoint_hits(root: Path, needles: list[str]) -> dict:
    """Grep the whole tree for the keypoint strings (binary files included)."""
    out: dict[str, list[str]] = {n: [] for n in needles}
    for p in root.rglob("*"):
        if not p.is_file() or p.is_symlink():
            continue
        try:
            data = p.read_bytes()
        except OSError:
            continue
        for n in needles:
            if n.encode("utf-8") in data:
                out[n].append(str(p.relative_to(root)))
    return out


