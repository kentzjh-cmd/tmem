#!/usr/bin/env python3
"""Build the carrier-ablation arms (docs/dsh-memory-carrier-ablation.md).

Factors
-------
carrier : tmem structured (.tmem/)   vs.  prose MD (MEMORY.md)
access  : automatic injection        vs.  on-demand read

Arms
----
  A1  tmem + automatic injection        (workspace plugin, hooks inject)
  A2  tmem + on-demand retrieval only   (same plugin, injection switched off)
  B1  prose MD + automatic injection    (md-carrier plugin, injects MEMORY.md)
  B2  prose MD + on-demand read         (no plugin; MEMORY.md is a file)
  C   no memory at all                  (no plugin, no MEMORY.md)

Content equivalence (CA-5)
-------------------------
The prose carrier is RENDERED from the same episode records that the tmem
carrier stores (render_prose_carrier.py) -- never written by hand or by a
model. So both carriers carry the same fact set, and the equivalence is
re-checkable with a grep.

Isolation
---------
* every arm/rep gets its own workspace copy and its own DSH_HOME;
* the control arms get a DSH_HOME whose cordis.patch.yml has NO tmem entry,
  and a PATH shim that refuses to run the global `tmem` CLI;
* the A2 arm gets a patched copy of the tmem package whose hook skips the
  auto-injection branch (single line, audited as a diff).

Usage
-----
  python3 build_arms.py seed   --exp-root /home/kent/e2e/abl
  python3 build_arms.py arms   --exp-root /home/kent/e2e/abl --reps 3
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HARNESS = Path("/home/kent/e2e/_harness")
ABL = Path("/home/kent/e2e/_harness/ablation")
REPO = Path("/archive/tmem")
REAL_HOME = Path.home() / ".dsh"

ARMS = ["A1", "A2", "B1", "B2", "C"]

NEUTRAL_AGENTS_TAIL = """
# 项目记忆指引（载体中立）

本项目过去的工程决策、修复顺序与验证方式记录在**项目记忆载体**里：

- 工作区若存在 `MEMORY.md`，那是散文式记忆载体，请查阅该文件；
- 工作区若存在 `.tmem/`（tmem 结构化记忆库），可用 `tmem lookup` / `tmem search` 检索。

不存在的载体直接忽略即可，不要凭空推测记忆内容。
"""

TMEM_AGENTS_MARKER = "# tmem Deterministic Engineering Memory & Milestone Protocol (DSH)"


# ---------------------------------------------------------------- utilities
def sh(cmd: list[str], cwd: Path | None = None, env: dict | None = None, timeout: int = 600):
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)


def normalize_agents_md(ws: Path) -> None:
    """Strip the tmem-specific protocol section; keep a carrier-neutral pointer.

    The installer appends a tmem protocol section to AGENTS.md. Leaving it in
    the tmem arms only would give those arms an extra instruction ("consult
    MEMORIES.md, use /tmem") that the prose arms do not get -> the arms would
    differ in more than the carrier. Both arms therefore get the SAME
    neutral pointer.
    """
    p = ws / "AGENTS.md"
    if not p.exists():
        p.write_text(NEUTRAL_AGENTS_TAIL.lstrip(), encoding="utf-8")
        return
    text = p.read_text(encoding="utf-8")
    idx = text.find(TMEM_AGENTS_MARKER)
    if idx >= 0:
        text = text[:idx].rstrip() + "\n"
    p.write_text(text.rstrip() + "\n" + NEUTRAL_AGENTS_TAIL, encoding="utf-8")


def strip_tmem_entry(patch_text: str) -> str:
    """Remove the tmem insert block from a cordis.patch.yml body."""
    block = """# 1) tmem plugin — Generated by tmem init for DeepSeek Harness (@deepseek-ai/dsh)
- insert:
    - id: tmem
      name: "/archive/tmem/tmem/dsh_plugin.mjs"

"""
    if block in patch_text:
        return patch_text.replace(block, "")
    # generic fallback: drop any "- id: tmem" entry block
    return re.sub(r"- insert:\n(?:\s+- id: tmem\n(?:.*\n)*?\n)*", "", patch_text)


def make_home(home: Path, with_md_carrier: bool) -> None:
    """Create an isolated DSH_HOME without the tmem plugin entry."""
    if home.exists():
        shutil.rmtree(home)
    home.mkdir(parents=True)
    prof = REAL_HOME / "profiles"
    if prof.exists():
        shutil.copytree(prof, home / "profiles")
    cred = REAL_HOME / ".credentials.yaml"
    if cred.exists():
        shutil.copy2(cred, home / ".credentials.yaml")
    patch = (REAL_HOME / "cordis.patch.yml").read_text(encoding="utf-8")
    patch = strip_tmem_entry(patch)
    if with_md_carrier:
        patch = patch.rstrip() + (
            "\n\n# carrier-ablation: prose MD injector (arm B1 only)\n"
            "- insert:\n"
            "    - id: md-carrier\n"
            f'      name: "{ABL / "md_carrier_plugin.mjs"}"\n'
        )
    (home / "cordis.patch.yml").write_text(patch, encoding="utf-8")


def make_shims(root: Path) -> tuple[Path, Path]:
    """PATH shims: A2 (patched tmem) and control arms (tmem refused)."""
    a2bin = root / "a2bin"
    blockbin = root / "blockbin"
    for d in (a2bin, blockbin):
        d.mkdir(parents=True, exist_ok=True)
    # A2: the plugin resolves the package root through the `tmem` on PATH.
    cli = root / "tmem-a2" / "tmem" / "cli.mjs"
    link = a2bin / "tmem"
    if link.exists() or link.is_symlink():
        link.unlink()
    link.symlink_to(cli)
    # control arms: no tmem CLI at all (trap #2 of the protocol)
    blk = blockbin / "tmem"
    blk.write_text(
        "#!/bin/sh\n"
        "echo '[ablation] the tmem CLI is not available in this arm' >&2\n"
        "exit 127\n",
        encoding="utf-8",
    )
    blk.chmod(0o755)
    return a2bin, blockbin


def patch_a2_package(root: Path) -> dict:
    """Copy the tmem package and switch the auto-injection branch off."""
    dst = root / "tmem-a2"
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(
        REPO,
        dst,
        ignore=shutil.ignore_patterns(".git", "node_modules", "docs", "*.tgz"),
    )
    hook = dst / "tmem" / "hooks" / "dsh.mjs"
    text = hook.read_text(encoding="utf-8")
    old = "    if (preBlocks.length > 0) {\n      return { injectedContext: preBlocks.join(\"\\n\\n\") };"
    new = (
        "    if (preBlocks.length > 0 && process.env.TMEM_ABLATE_NO_INJECT !== \"1\") {\n"
        "      return { injectedContext: preBlocks.join(\"\\n\\n\") };"
    )
    if old not in text:
        print("[build] FATAL: injection branch not found in hooks/dsh.mjs")
        raise SystemExit(6)
    hook.write_text(text.replace(old, new, 1), encoding="utf-8")
    # also keep the CLI entry point resolvable for the PATH shim
    return {
        "patched_root": str(dst),
        "patched_file": str(hook),
        "patch": "if (preBlocks.length > 0 && process.env.TMEM_ABLATE_NO_INJECT !== \"1\")",
        "env": "TMEM_ABLATE_NO_INJECT=1",
    }


# ------------------------------------------------------------------ phase: seed
def phase_seed(root: Path) -> None:
    seed = root / "seed"
    seed.parent.mkdir(parents=True, exist_ok=True)
    if not (seed / ".git").exists():
        if seed.exists():
            shutil.rmtree(seed)
        print("[build] building fixture ...", flush=True)
        r = sh([sys.executable, str(HARNESS / "build_fixture.py"), "--dest", str(seed)], timeout=900)
        if r.returncode != 0:
            print("[build] FATAL: fixture build failed:", r.stderr[-800:])
            raise SystemExit(3)
    print("[build] installing plugin in the seed workspace ...", flush=True)
    # `tmem init` also touches the HOME-level patch. We run it against a
    # throwaway DSH_HOME so the real ~/.dsh/cordis.patch.yml is never modified
    # (the real home is shared with the concurrently running Round 3 B arm,
    # which removes the tmem entry from it on purpose).
    env = dict(os.environ)
    env["DSH_HOME"] = str(root / "homes" / "init-tmp")
    r = sh(["tmem", "init"], cwd=seed, env=env, timeout=300)
    print("[build] tmem init exit:", r.returncode, r.stdout.strip()[-200:], r.stderr.strip()[-200:])
    normalize_agents_md(seed)
    print("[build] seed workspace ready:", seed)


# ------------------------------------------------------------------ phase: arms
def phase_arms(root: Path, reps: int) -> None:
    # the seed workspace is named `ledger-svc` so that the shared scene runner
    # (run_scenes.py, workspace kind "exp") can drive it
    seed = root / "ledger-svc" if (root / "ledger-svc" / ".tmem").exists() else root / "seed"
    store = seed / ".tmem"
    if not store.exists():
        print("[build] FATAL: seed has no .tmem store -- run the seeding scenes first")
        raise SystemExit(4)

    # 1. prose carrier rendered from the very same episode records
    print("[build] rendering the prose carrier ...", flush=True)
    r = sh([sys.executable, str(ABL / "render_prose_carrier.py"), "--src", str(seed), "--out", str(root / "carrier")], timeout=300)
    print(r.stdout.strip())
    if r.returncode != 0:
        print("[build] FATAL: carrier equivalence check failed")
        raise SystemExit(5)
    prose = (root / "carrier" / "MEMORY.md").read_text(encoding="utf-8")

    # 2. isolated homes + PATH shims
    make_home(root / "homes" / "plain", with_md_carrier=False)
    make_home(root / "homes" / "md", with_md_carrier=True)
    a2info = patch_a2_package(root)
    (root / "a2_patch.json").write_text(json.dumps(a2info, ensure_ascii=False, indent=2), encoding="utf-8")
    make_shims(root)

    # 3. arms
    manifest = []
    for arm in ARMS:
        for rep in range(1, reps + 1):
            ws = root / "arms" / arm / f"rep{rep}"
            if ws.exists():
                shutil.rmtree(ws)
            ws.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(seed, ws, symlinks=True)
            home = root / "homes" / ("md" if arm == "B1" else "plain")
            entry = {"arm": arm, "rep": rep, "workspace": str(ws), "dsh_home": str(home)}

            # git hook: the official install adds a post-commit hook that calls
            # `tmem capture`; the control arms must not have it.
            hook = ws / ".git" / "hooks" / "post-commit"
            if hook.exists():
                hook.unlink()

            if arm in ("A1", "A2"):
                # keep the seeded .tmem store, (re)install the plugin officially
                env = dict(os.environ)
                env["DSH_HOME"] = str(root / "homes" / "init-tmp")
                r = sh(["tmem", "init"], cwd=ws, env=env, timeout=300)
                entry["tmem_init_exit"] = r.returncode
                normalize_agents_md(ws)
                entry["patch"] = str(ws / ".dsh" / "tmem.patch.yml")
            else:
                # control arms: no tmem store at all
                if (ws / ".tmem").exists():
                    shutil.rmtree(ws / ".tmem")
                for f in ("MEMORIES.md", "MEM.md"):
                    p = ws / f
                    if p.exists() or p.is_symlink():
                        p.unlink()
                if arm in ("B1", "B2"):
                    (ws / "MEMORY.md").write_text(prose, encoding="utf-8")
                    entry["memory_md_bytes"] = len(prose.encode("utf-8"))
                if arm == "B1":
                    d = ws / ".dsh"
                    d.mkdir(exist_ok=True)
                    (d / "md-carrier.patch.yml").write_text(
                        "# carrier-ablation: prose MD injector\n"
                        "- insert:\n"
                        "    - id: md-carrier\n"
                        f'      name: "{ABL / "md_carrier_plugin.mjs"}"\n',
                        encoding="utf-8",
                    )
                    entry["patch"] = str(ws / ".dsh" / "md-carrier.patch.yml")

            entry["has_tmem_store"] = (ws / ".tmem").exists()
            entry["has_memory_md"] = (ws / "MEMORY.md").exists()
            manifest.append(entry)
            print(
                "[build] %s rep%d: store=%s memory_md=%s home=%s"
                % (arm, rep, entry["has_tmem_store"], entry["has_memory_md"], home.name),
                flush=True,
            )

    (root / "arms_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print("[build] manifest ->", root / "arms_manifest.json")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("phase", choices=["seed", "arms"])
    ap.add_argument("--exp-root", default="/home/kent/e2e/abl")
    ap.add_argument("--reps", type=int, default=3)
    args = ap.parse_args()
    root = Path(args.exp_root)
    if args.phase == "seed":
        phase_seed(root)
    else:
        phase_arms(root, args.reps)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
